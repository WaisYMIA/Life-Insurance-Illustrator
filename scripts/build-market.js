/* Builds market-data.js from data/market-src/*.json: node scripts/build-market.js */
const fs = require('fs'), path = require('path');
const SRC = path.join(__dirname, '..', 'data', 'market-src');
const META = {
  jubilee: ['Jubilee Life', ['jubileeinsurance.com']], britam: ['Britam Life', ['ke.britam.com']],
  'icea-lion': ['ICEA LION Life', ['icealion.com']], liberty: ['Liberty Life', ['liberty.co.ke', 'libertykenya.co.ke']],
  kenindia: ['Kenindia Assurance', ['kenindia.co.ke']], 'cic-life': ['CIC Life', ['cicinsurancegroup.com']],
  'old-mutual': ['Old Mutual Kenya', ['oldmutual.co.ke']], sanlam: ['SanlamAllianz Kenya', ['sanlamallianz.com', 'akibaplus.co.ke']],
  'apa-life': ['APA Life', ['apalife.co.ke']], pioneer: ['Pioneer Assurance', ['pioneerinsurance.co.ke']],
  'ga-life': ['GA Life', ['gainsuranceltd.com']], madison: ['Madison Life', ['madison.co.ke']], prudential: ['Prudential Life', ['prudential.co.ke']]
};
const CATS = ['term-life','whole-life','endowment-savings','education','investment-linked','funeral-family-protection','credit-mortgage','pension-retirement','group','other'];
const CONTACT = /contact|enquir|\bsms\b|call ?back|book a call|apply via|whatsapp|@|\+?\d{9,}|https?:\/\//i;
const clean = x => String(x).replace(/\(?https?:\/\/\S+?\)?(?=[\s;,]|$)/g, '').trim();
const arr = v => Array.isArray(v) ? v.filter(Boolean).map(String) : (v ? [String(v)] : []);
const str = v => (v == null || v === '' ? '' : String(v));
const insurers = [];
for(const id of Object.keys(META)){
  const f = path.join(SRC, id + '.json'); if(!fs.existsSync(f)) continue;
  const d = JSON.parse(fs.readFileSync(f, 'utf8'));
  const ins = { id, name: META[id][0], note: str(d.insurer_note), checked: d.checked, products: [] };
  for(const p of d.products || []){
    let host = ''; try{ host = new URL(p.source_url).hostname.replace(/^www\./, ''); }catch(e){}
    const official = META[id][1].some(h => host === h || host.endsWith('.' + h));
    ins.products.push({ id: id + '-' + p.name.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, ''), name: p.name,
      cat: CATS.includes(p.category) ? p.category : 'other', summary: str(p.summary), client: str(p.target_client), how: str(p.how_it_works),
      features: arr(p.key_features), benefits: arr(p.benefits), riders: arr(p.riders_options), age: str(p.entry_age), term: str(p.term_or_duration),
      min: str(p.min_premium_or_sum_assured), pay: str(p.payment_options), excl: str(p.waiting_periods_or_exclusions),
      distinct: arr(p.channels_or_distinct_points).filter(x => !CONTACT.test(x)), pros: arr(p.analysis_selling_points), cons: arr(p.analysis_watch_outs),
      src: host, official, brochure: !!p.brochure, srcNote: clean(str(p.source_note)) });
    const q = ins.products[ins.products.length - 1]; if(!q.cons.length) q.cons.push('Little detail published on the source page; get the brochure before advising.');
  }
  insurers.push(ins);
}
const out = { built: new Date().toISOString().slice(0, 10), insurers };
fs.writeFileSync(path.join(__dirname, '..', 'market-data.js'), '/* Generated by scripts/build-market.js from data/market-src/*.json. Desk research from public pages; verify with official documents. */\nwindow.MARKET_DATA = ' + JSON.stringify(out) + ';\n');
const n = insurers.reduce((a, i) => a + i.products.length, 0);
console.log('market-data.js:', insurers.length, 'insurers,', n, 'products,', insurers.reduce((a, i) => a + i.products.filter(p => p.official).length, 0), 'from official pages');
